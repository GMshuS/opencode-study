import { Plugin } from "@opencode/plugin"
import { createHash } from "crypto"
import { tmpdir } from "os"
import path from "path"
import { promises as fs } from "fs"

const TMP_DIR = path.join(tmpdir(), "opencode-vision")

// Map from content hash → global image sequence number, ensuring each unique
// image gets a stable seq across the session.
const imageRegistry = new Map<string, number>()
// Reverse map: seq → hash, used to clean imageRegistry when LRU evicts a dir.
const reverseRegistry = new Map<number, string>()
let nextImageSeq = 1

// LRU eviction: when this many images are stored, oldest image* dir gets deleted
// Default 200 images (~200MB cap); adjustable via VISION_MAX_IMAGES env var
const MAX_IMAGES = Number(process.env["VISION_MAX_IMAGES"] || 200)
const LRU_QUEUE: string[] = []  // image{N} dir paths in access order (deduplicated)

// Shared prefix for all plugin-injected hint text parts. Used by both hint
// generation and isPluginInjectedText() cleanup to stay in sync.
const HINT_PREFIX = "[opencode-vision:"

/**
 * Record access for LRU eviction. Deduplicates the queue so the same seqDir
 * is never counted twice — prevents queue bloat and accidental eviction of
 * in-use directories when the same image is referenced multiple times.
 */
function touchLRU(seqDir: string) {
  // Step 1: remove old occurrence to "move to back" (O(n) but n ≤ MAX_IMAGES)
  const idx = LRU_QUEUE.indexOf(seqDir)
  if (idx !== -1) LRU_QUEUE.splice(idx, 1)
  LRU_QUEUE.push(seqDir)

  // Step 2: evict oldest entries when over the cap
  while (LRU_QUEUE.length > MAX_IMAGES) {
    const oldest = LRU_QUEUE.shift()
    if (!oldest) break
    // Extract seq number from dir name (e.g. "image42" → 42) to clean registries
    const seqMatch = oldest.match(/image(\d+)$/)
    if (seqMatch) {
      const evictedSeq = Number(seqMatch[1])
      const evictedHash = reverseRegistry.get(evictedSeq)
      if (evictedHash) {
        imageRegistry.delete(evictedHash)
        reverseRegistry.delete(evictedSeq)
      }
    }
    // Asynchronously delete the oldest image dir
    fs.rm(oldest, { recursive: true, force: true }).catch(() => {})
  }
}

// Identifies text parts that THIS plugin injected into a user message during a
// previous transform run. The hook re-runs for every model request (including
// after a /model switch), so we must clear these stale injections on every pass
// — otherwise native-vision models would see the "[vision: imageN/hash.ext]"
// placeholder text and incorrectly call the vision tool to "read" it, instead of
// viewing the original image part natively.
function isPluginInjectedText(text: string): boolean {
  if (!text) return false
  // Primary check: all hints generated by this plugin share HINT_PREFIX.
  // Legacy patterns kept for backward compat with messages created before
  // the prefix was introduced.
  return (
    text.startsWith(HINT_PREFIX) ||
    /^\[Image #\d+ auto-saved to /.test(text) ||
    /^\[Image #\d+ \w+\.\w+ auto-saved to /.test(text) ||
    /^\[Images auto-saved to:/.test(text) ||
    /^\[Images \(\d+\) auto-saved to:/.test(text) ||
    /^\[vision: image\d+\/[\w-]+\.[\w]+]$/.test(text)
  )
}

// ── Delegation mode ──
//
// VISION_MODE controls how non-vision models obtain image descriptions:
//   "api"      (default, original) — the vision tool calls an external VLM
//              API (VISION_API_KEY + VISION_API_URL).
//   "subagent" — the plugin instructs the LLM to delegate image analysis to
//              the @image-reader subagent. No external API key is required.
//
// Auto-fallback: when VISION_MODE is unset, the plugin uses "api" mode if
// VISION_API_KEY is present, otherwise it falls back to "subagent" mode.
const VISION_MODE_RAW = (process.env["VISION_MODE"] || "").toLowerCase()
const VISION_SUBAGENT_NAME = process.env["VISION_SUBAGENT_NAME"] || "image-reader"
const hasApiKey = !!process.env["VISION_API_KEY"]
const VISION_MODE: "api" | "subagent" =
  VISION_MODE_RAW === "subagent" ? "subagent" :
  VISION_MODE_RAW === "api" ? "api" :
  hasApiKey ? "api" : "subagent"

// ── V2 消息结构辅助 ──
//
// V1 的用户消息是 { info, parts }，图片在 part.type === "file" 的 data URL 里。
// V2 的消息是 @opencode/ai 的 Message：{ role, content }，图片变成
// content 里 type === "media" 的片段，真正的数据在 part.media.source 上。
interface MediaSource {
  type?: "base64" | "bytes" | "url" | "ref"
  data?: string | Uint8Array
  mediaType?: string
  url?: string
}

interface ContentPart {
  type?: string
  text?: string
  media?: { source?: MediaSource }
}

interface AiMessage {
  role?: string
  content: ContentPart[]
}

/** 从 media 片段里取出 base64 数据和 mime，取不到时返回 undefined */
function extractImage(part: ContentPart): { base64: string; mime: string } | undefined {
  const source = part.media?.source
  if (!source) return undefined

  if (source.type === "base64" && typeof source.data === "string") {
    return { base64: source.data, mime: source.mediaType || "image/png" }
  }

  if (source.type === "bytes" && source.data) {
    const bytes = source.data instanceof Uint8Array ? source.data : Buffer.from(String(source.data), "base64")
    return { base64: Buffer.from(bytes).toString("base64"), mime: source.mediaType || "image/png" }
  }

  if (source.type === "url" && source.url) {
    // data URL（data:image/png;base64,....）可以直接解析；远程/本地文件跳过
    const match = /^data:([^;,]+);base64,(.*)$/s.exec(source.url)
    if (!match) return undefined
    return { base64: match[2], mime: match[1] }
  }

  return undefined
}

async function fileExists(filePath: string): Promise<boolean> {
  try {
    await fs.access(filePath)
    return true
  } catch {
    return false
  }
}

/**
 * OpenCode V2 插件：让不支持图片的模型也能“看图”
 *
 * V1 → V2 的钩子迁移：
 *   - 'experimental.chat.system.transform'   → ctx.session.hook('context')，改 event.system
 *   - 'experimental.chat.messages.transform' → ctx.session.hook('context')，改 event.messages
 *   - 'tool.definition'                      → ctx.tool.transform(editor => editor.update(...))
 *   - 'tool.execute.before'                  → ctx.tool.hook('execute.before')
 *
 * 行为保持不变：
 *  1. 每条带图片的用户消息，把图片落盘到临时目录，并在消息末尾追加路径提示
 *  2. 原生支持图片的模型：注入“可以直接看图”的系统提示，并禁用 vision 工具
 *  3. 不支持图片的模型：在 subagent 模式下提示交给 @image-reader 子代理
 */
export default Plugin.define({
  id: "vision-helper",
  async setup(ctx) {
    // Ensure the temp root dir exists at plugin startup
    await fs.mkdir(TMP_DIR, { recursive: true }).catch(() => {})

    // 记录当前模型/会话是否原生支持图片（V1 用同一个模块级状态）
    let currentModelSupportsImage = false
    const sessionImageSupport = new Map<string, boolean>()

    const modelSupportsImage = (sessionID?: string): boolean =>
      sessionID ? (sessionImageSupport.get(sessionID) ?? currentModelSupportsImage) : currentModelSupportsImage

    const nativeVisionBlockArgs = () => ({
      paths: [],
      __nativeVisionBlocked: true,
    })

    /** 查询模型是否原生支持图片输入（V2 的 capabilities.input 是模态字符串数组） */
    const lookupImageSupport = async (model: { providerID: string; id: string }): Promise<boolean> => {
      try {
        // V2 的 model.list() 返回 { location, data }，不是数组
        const { data } = await ctx.model.list()
        const found = data.find(
          (item) => item.providerID === model.providerID && (item.modelID === model.id || item.id === model.id),
        )
        return !!found?.capabilities?.input?.includes("image")
      } catch {
        return false
      }
    }

    /** 把用户消息里的图片落盘，并追加一条路径提示文本 */
    const injectImageHints = async (messages: AiMessage[]) => {
      for (const msg of messages) {
        if (msg.role !== "user") continue
        if (!Array.isArray(msg.content)) continue

        // 跳过压缩消息（里面已经有压缩片段，不含原始图片）
        if (msg.content.some((part) => part.type === "compaction")) continue

        // 清理上一次 transform 注入的文本，避免切换模型后提示重复堆积
        for (let i = msg.content.length - 1; i >= 0; i--) {
          const part = msg.content[i]
          if (part.type === "text" && typeof part.text === "string" && isPluginInjectedText(part.text)) {
            msg.content.splice(i, 1)
          }
        }

        if (modelSupportsImage()) continue

        const saved: { name: string; seq: number }[] = []

        for (const part of msg.content) {
          if (part.type !== "media") continue

          const image = extractImage(part)
          if (!image || !image.mime.startsWith("image/")) continue

          const base64 = image.base64
          if (!base64) continue

          // MD5 over the FULL base64 (not just a prefix) to avoid collisions
          // for visually similar images. 16 hex chars (64 bits).
          const hash = createHash("md5").update(base64).digest("hex").slice(0, 16)

          let seq = imageRegistry.get(hash)
          if (!seq) {
            seq = nextImageSeq++
            imageRegistry.set(hash, seq)
            reverseRegistry.set(seq, hash)
          }

          const ext = image.mime.split("/")[1] || "png"
          const name = `${hash}.${ext}`

          const seqDir = path.join(TMP_DIR, `image${seq}`)
          const filePath = path.join(seqDir, name)
          // 写盘失败降级为跳过，不打断本轮对话
          if (!(await fileExists(filePath))) {
            try {
              await fs.mkdir(seqDir, { recursive: true }).catch(() => {})
              await fs.writeFile(filePath, Buffer.from(base64, "base64"))
            } catch (err) {
              console.error(`[vision-helper] Failed to write ${filePath}:`, err)
              continue
            }
          }

          touchLRU(seqDir)
          saved.push({ name, seq })
        }

        if (saved.length === 0) continue

        // 路径提示：api 模式是中性的，subagent 模式会点名 @image-reader
        const hintSuffix = VISION_MODE === "subagent"
          ? ` — use @${VISION_SUBAGENT_NAME} subagent via the subagent tool to analyze it if you cannot view images natively]`
          : `]`

        const hints = saved.length === 1
          ? `${HINT_PREFIX} Image #${saved[0].seq} ${saved[0].name} auto-saved to ${path.join(TMP_DIR, `image${saved[0].seq}`, saved[0].name)}${hintSuffix}`
          : `${HINT_PREFIX} Images (${saved.length}) auto-saved to:\n${saved.map((s) => `  ${path.join(TMP_DIR, `image${s.seq}`, s.name)}`).join("\n")}${hintSuffix}`

        msg.content.push({ type: "text", text: hints })
      }
    }

    // ══════════════════════════════════════════════════════════════════════
    // 1. 系统提示 + 消息改写（V1: system.transform + messages.transform）
    // ══════════════════════════════════════════════════════════════════════
    await ctx.session.hook("context", async (event) => {
      const hasImage = await lookupImageSupport(event.model)
      currentModelSupportsImage = hasImage
      sessionImageSupport.set(event.sessionID, hasImage)

      let instruction: string | undefined
      if (hasImage) {
        instruction = "You have native image input capabilities. You can directly view and analyze images attached to user messages. Do NOT call the `vision` tool to read images sent by the user — analyze them natively instead."
      } else if (VISION_MODE === "subagent") {
        instruction = `IMPORTANT: This model does NOT support image input. When a user attaches an image or screenshot, the plugin saves it to a temp directory and appends a path hint like '${HINT_PREFIX} Image #1 abc.png auto-saved to ...'. You MUST delegate image analysis to the @${VISION_SUBAGENT_NAME} subagent (subagent="${VISION_SUBAGENT_NAME}", prompt="Read and describe the image at <path>"). The @${VISION_SUBAGENT_NAME} subagent runs on a multimodal model that can read images. Never attempt to read images directly with the \`read\` tool — it will fail with 'model does not support image input'.`
      }

      if (instruction) {
        event.system.push({ type: "text", text: instruction })
      }

      await injectImageHints(event.messages as unknown as AiMessage[])
    })

    // ══════════════════════════════════════════════════════════════════════
    // 2. vision 工具描述（V1: 'tool.definition'）
    // ══════════════════════════════════════════════════════════════════════
    // V2 的 transform 是同步、可重放的，无法按“当前模型”动态改写描述，
    // 因此这里写成同时覆盖两种情况的说明；模型相关的引导放在系统提示里。
    // 如果 vision 工具不存在（例如没有 VISION_API_KEY），update 会被忽略。
    await ctx.tool.transform((editor) => {
      editor.update("vision", (tool) => {
        tool.description = [
          "Reads one or more image files via an external VLM API and returns a textual description.",
          "Use ONLY for text-only models that cannot parse image attachments.",
          "Native-vision models should analyze user-attached images directly or use the built-in `read` tool for local image files — for those models this tool is disabled and returns an error.",
        ].join("\n")
      })
    })

    // ══════════════════════════════════════════════════════════════════════
    // 3. 原生支持图片时禁用 vision 工具（V1: 'tool.execute.before'）
    // ══════════════════════════════════════════════════════════════════════
    await ctx.tool.hook("execute.before", (event) => {
      if (event.tool === "vision" && modelSupportsImage(event.sessionID)) {
        event.input = nativeVisionBlockArgs()
      }
    })
  },
})
