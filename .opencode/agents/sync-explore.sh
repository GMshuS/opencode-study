#!/bin/bash
# 同步 explore agent 的分发副本。
#
# 唯一手写源：  .opencode/agents/explore/       （explore.md + templates/）
# 生成副本：    .codebuddy/agents/explore/      （正文同步 + templates/ 副本）
#
# 之后由两侧的 development.sh 整目录复制到用户目录，
# 使 agent 定义与其同级的 templates/ 一起分发。
# 修改模板请改源目录，然后重新运行本脚本。

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SRC="$ROOT/.opencode/agents/explore"
DST="$ROOT/.codebuddy/agents/explore"
MARK="# GENERATED by .opencode/agents/sync-explore.sh -- edit the source under .opencode/agents/explore/templates/"

fail() { echo "ERROR: $*" >&2; exit 1; }

# 0. 源完整性：模板齐全且元信息完整（与 agent 定义的候选门槛一致）
[ -f "$SRC/explore.md" ] || fail "missing $SRC/explore.md"
for n in generic backend frontend; do
  [ -f "$SRC/templates/$n.md" ] || fail "missing $SRC/templates/$n.md"
  grep -q '^name: '    "$SRC/templates/$n.md" || fail "$n.md: missing name"
  grep -q '^version: ' "$SRC/templates/$n.md" || fail "$n.md: missing version"
  grep -q '^schema: '  "$SRC/templates/$n.md" || fail "$n.md: missing schema"
done

# 1. 正文同步：保留 codebuddy 的 yaml 头，正文以 "# 探索模式" 为界
{
  awk '/^# 探索模式/{exit} {print}' "$DST/explore.md"
  awk '/^# 探索模式/{p=1} p'        "$SRC/explore.md"
} > "$DST/explore.md.tmp"
mv "$DST/explore.md.tmp" "$DST/explore.md"

# 2. templates 副本：frontmatter 内插入生成标记，副本不手写
mkdir -p "$DST/templates"
for n in generic backend frontend; do
  awk -v m="$MARK" 'NR==1 { cr = ($0 ~ /\r$/) ? "\r" : ""; print; print m cr; next } {print}' \
    "$SRC/templates/$n.md" > "$DST/templates/$n.md"
done

# 3. 一致性校验：按字节比较正文（awk 会规范化末尾换行，不能用它做比较）
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

byte_body() {  # $1=文件 $2=输出；以 "# 探索模式" 的字节偏移截取原始正文
  local off
  off="$(grep -abo '^# 探索模式' "$1" | head -n1 | cut -d: -f1)"
  [ -n "$off" ] || fail "$1: missing body marker"
  tail -c +"$((off + 1))" "$1" > "$2"
}
byte_body "$SRC/explore.md" "$TMP/src.body"
byte_body "$DST/explore.md" "$TMP/dst.body"
cmp -s "$TMP/src.body" "$TMP/dst.body" \
  || fail "explore.md body out of sync (byte-level)"

for n in generic backend frontend; do
  grep -vF "$MARK" "$DST/templates/$n.md" > "$TMP/$n.body"
  cmp -s "$TMP/$n.body" "$SRC/templates/$n.md" \
    || fail "$n.md out of sync (byte-level)"
done

echo "OK: explore.md body + 3 templates synced to .codebuddy/agents/explore/"
